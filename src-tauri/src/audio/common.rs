/// Platform-independent audio definitions shared by the desktop (rodio) and
/// mobile (Kotlin bridge) audio managers, and by the WebSocket server when it
/// ships the active sound bytes to a paired phone.
///
/// Sound resolution order for every cue:
///   1. custom file in `{app_data_dir}/audio/custom_<cue>.<ext>`
///   2. bundled preset selected in settings (`sound_<cue>` = preset id)
///   3. embedded default asset
use std::path::Path;

use crate::settings::Settings;

// ---------------------------------------------------------------------------
// Embedded audio assets
// ---------------------------------------------------------------------------

const ALERT_WORK: &[u8] = include_bytes!("../../../static/audio/alert-work.mp3");
const ALERT_SHORT_BREAK: &[u8] = include_bytes!("../../../static/audio/alert-short-break.mp3");
const ALERT_LONG_BREAK: &[u8] = include_bytes!("../../../static/audio/alert-long-break.mp3");
const TICK: &[u8] = include_bytes!("../../../static/audio/tick.mp3");

/// Bundled preset sounds, generated by `scripts/gen_presets.py`.
/// The ids are what the `sound_*` settings store.
pub const PRESETS: &[(&str, &[u8])] = &[
    ("bell", include_bytes!("../../../static/audio/presets/bell.wav")),
    ("chime", include_bytes!("../../../static/audio/presets/chime.wav")),
    ("digital", include_bytes!("../../../static/audio/presets/digital.wav")),
    ("marimba", include_bytes!("../../../static/audio/presets/marimba.wav")),
    ("soft", include_bytes!("../../../static/audio/presets/soft.wav")),
];

/// Value of a `sound_*` setting that selects the embedded default asset.
pub const SOUND_DEFAULT: &str = "default";

pub fn preset_bytes(id: &str) -> Option<&'static [u8]> {
    PRESETS.iter().find(|(name, _)| *name == id).map(|(_, b)| *b)
}

// ---------------------------------------------------------------------------
// Cues
// ---------------------------------------------------------------------------

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AudioCue {
    WorkAlert,
    ShortBreakAlert,
    LongBreakAlert,
    Tick,
}

/// Fixed file stems used when copying custom audio files into the config dir.
pub const STEM_WORK: &str = "custom_work_alert";
pub const STEM_SHORT: &str = "custom_short_break_alert";
pub const STEM_LONG: &str = "custom_long_break_alert";
pub const STEM_TICK: &str = "custom_tick";

impl AudioCue {
    pub const ALL: [AudioCue; 4] = [
        AudioCue::WorkAlert,
        AudioCue::ShortBreakAlert,
        AudioCue::LongBreakAlert,
        AudioCue::Tick,
    ];

    /// Parse the frontend/IPC identifier (`"work_alert"`, `"tick"`, ...).
    pub fn from_key(key: &str) -> Option<Self> {
        match key {
            "work_alert" => Some(Self::WorkAlert),
            "short_break_alert" => Some(Self::ShortBreakAlert),
            "long_break_alert" => Some(Self::LongBreakAlert),
            "tick" => Some(Self::Tick),
            _ => None,
        }
    }

    pub fn key(self) -> &'static str {
        match self {
            Self::WorkAlert => "work_alert",
            Self::ShortBreakAlert => "short_break_alert",
            Self::LongBreakAlert => "long_break_alert",
            Self::Tick => "tick",
        }
    }

    /// File stem of the custom file for this cue.
    pub fn stem(self) -> &'static str {
        match self {
            Self::WorkAlert => STEM_WORK,
            Self::ShortBreakAlert => STEM_SHORT,
            Self::LongBreakAlert => STEM_LONG,
            Self::Tick => STEM_TICK,
        }
    }

    /// Settings key that persists the original display name of the custom file.
    pub fn name_key(self) -> &'static str {
        match self {
            Self::WorkAlert => "custom_work_alert_name",
            Self::ShortBreakAlert => "custom_short_break_alert_name",
            Self::LongBreakAlert => "custom_long_break_alert_name",
            Self::Tick => "custom_tick_name",
        }
    }

    /// Settings key that stores the selected preset id (or `"default"`).
    pub fn sound_key(self) -> &'static str {
        match self {
            Self::WorkAlert => "sound_work_alert",
            Self::ShortBreakAlert => "sound_short_break_alert",
            Self::LongBreakAlert => "sound_long_break_alert",
            Self::Tick => "sound_tick",
        }
    }

    /// Embedded default asset for this cue.
    pub fn default_bytes(self) -> &'static [u8] {
        match self {
            Self::WorkAlert => ALERT_WORK,
            Self::ShortBreakAlert => ALERT_SHORT_BREAK,
            Self::LongBreakAlert => ALERT_LONG_BREAK,
            Self::Tick => TICK,
        }
    }
}

