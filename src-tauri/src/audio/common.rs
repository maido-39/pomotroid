/// Which preset (or `"default"`) each cue uses, mirrored from `Settings`.
#[derive(Debug, Clone, PartialEq)]
pub struct SoundSelection {
    pub work_alert: String,
    pub short_break_alert: String,
    pub long_break_alert: String,
    pub tick: String,
}

impl SoundSelection {
    pub fn get(&self, cue: AudioCue) -> &str {
        match cue {
            AudioCue::WorkAlert => &self.work_alert,
            AudioCue::ShortBreakAlert => &self.short_break_alert,
            AudioCue::LongBreakAlert => &self.long_break_alert,
            AudioCue::Tick => &self.tick,
        }
    }
}

impl From<&Settings> for SoundSelection {
    fn from(s: &Settings) -> Self {
        Self {
            work_alert: s.sound_work_alert.clone(),
            short_break_alert: s.sound_short_break_alert.clone(),
            long_break_alert: s.sound_long_break_alert.clone(),
            tick: s.sound_tick.clone(),
        }
    }
}

impl Default for SoundSelection {
    fn default() -> Self {
        Self::from(&Settings::default())
    }
}

/// Resolved bytes for a cue plus a MIME type suitable for HTTP/JS playback.
#[derive(Debug, Clone)]
pub struct AudioSource {
    pub bytes: Vec<u8>,
    pub mime: &'static str,
    /// `"custom"`, a preset id, or `"default"` — for logging and the UI.
    pub origin: String,
}

pub fn mime_for_path(path: &Path) -> &'static str {
    match path
        .extension()
        .and_then(|e| e.to_str())
        .map(|e| e.to_ascii_lowercase())
        .as_deref()
    {
        Some("wav") => "audio/wav",
        Some("ogg") | Some("oga") => "audio/ogg",
        Some("flac") => "audio/flac",
        Some("m4a") | Some("aac") => "audio/mp4",
        _ => "audio/mpeg",
    }
}

/// Resolve the active sound for `cue`: custom file → preset → default.
/// A custom file that cannot be read falls through to the next option.
pub fn resolve_source(cue: AudioCue, custom: Option<&Path>, selection: &SoundSelection) -> AudioSource {
    if let Some(path) = custom {
        match std::fs::read(path) {
            Ok(bytes) => {
                return AudioSource { bytes, mime: mime_for_path(path), origin: "custom".into() };
            }
            Err(e) => log::warn!("[audio] cannot read custom file {path:?}: {e}"),
        }
    }
    let selected = selection.get(cue);
    if selected != SOUND_DEFAULT {
        if let Some(bytes) = preset_bytes(selected) {
            return AudioSource { bytes: bytes.to_vec(), mime: "audio/wav", origin: selected.to_string() };
        }
        log::warn!("[audio] unknown preset '{selected}' for {} — using default", cue.key());
    }
    AudioSource { bytes: cue.default_bytes().to_vec(), mime: "audio/mpeg", origin: SOUND_DEFAULT.into() }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_assets_are_non_empty() {
        for cue in AudioCue::ALL {
            assert!(!cue.default_bytes().is_empty(), "{} default is empty", cue.key());
        }
        for (id, bytes) in PRESETS {
            assert!(!bytes.is_empty(), "preset {id} is empty");
            assert!(bytes.starts_with(b"RIFF"), "preset {id} is not a WAV file");
        }
    }

    #[test]
    fn cue_key_round_trip() {
        for cue in AudioCue::ALL {
            assert_eq!(AudioCue::from_key(cue.key()), Some(cue));
        }
        assert_eq!(AudioCue::from_key("nope"), None);
    }

    #[test]
    fn safe_extension_sanitises() {
        assert_eq!(safe_extension("song.MP3"), "mp3");
        assert_eq!(safe_extension("bell.wav"), "wav");
        assert_eq!(safe_extension("noext"), "mp3");
        assert_eq!(safe_extension("weird.w a v"), "mp3");
    }

    #[test]
    fn resolve_prefers_custom_then_preset_then_default() {
        let dir = std::env::temp_dir().join(format!("pomotroid-audio-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let custom = dir.join("custom_tick.wav");
        std::fs::write(&custom, b"RIFFfake").unwrap();

        let mut sel = SoundSelection::default();
        sel.tick = "bell".into();

        let src = resolve_source(AudioCue::Tick, Some(&custom), &sel);
        assert_eq!(src.origin, "custom");
        assert_eq!(src.mime, "audio/wav");
        assert_eq!(src.bytes, b"RIFFfake");

        let src = resolve_source(AudioCue::Tick, None, &sel);
        assert_eq!(src.origin, "bell");
        assert_eq!(src.bytes, preset_bytes("bell").unwrap());

        sel.tick = SOUND_DEFAULT.into();
        let src = resolve_source(AudioCue::Tick, None, &sel);
        assert_eq!(src.origin, SOUND_DEFAULT);
        assert_eq!(src.bytes, AudioCue::Tick.default_bytes());

        // Unknown preset falls back to default.
        sel.tick = "does-not-exist".into();
        let src = resolve_source(AudioCue::Tick, None, &sel);
        assert_eq!(src.origin, SOUND_DEFAULT);

        // Unreadable custom path falls through.
        let src = resolve_source(AudioCue::Tick, Some(&dir.join("missing.wav")), &sel);
        assert_eq!(src.origin, SOUND_DEFAULT);

        std::fs::remove_dir_all(&dir).ok();
    }

}
